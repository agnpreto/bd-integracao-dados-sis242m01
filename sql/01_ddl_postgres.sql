-- DDL corrigido (PostgreSQL)
-- Correções em relação a sql/01_ddl_enunciado.sql:
--  * entradas_mercadoria: coluna ordem_compra adicionada (a PK a referenciava, mas ela não existia)
--  * produtos_filial: vírgula faltando antes do CONSTRAINT; PK usava idproduto (o correto é produto_id)
--  * fornecedor: PK usava idproduto (inexistente); nome idforncedor corrigido para idfornecedor
--  * typos: decricao -> descricao, idfonecedor -> idfornecedor
--  * tipos padronizados (filial_id integer, produto_id varchar(25), dinheiro em numeric)
--  * float8 em pedido_id/item/ordem_compra trocado por bigint/integer
--  * FKs para fornecedor; fornecedor criada antes das tabelas que a referenciam

CREATE TABLE fornecedor (
  idfornecedor integer GENERATED BY DEFAULT AS IDENTITY,
  razao_social varchar(255) NOT NULL,
  CONSTRAINT fornecedor_pkey PRIMARY KEY (idfornecedor)
);

CREATE TABLE produtos_filial (
  filial_id      integer      NOT NULL,
  produto_id     varchar(25)  NOT NULL,
  descricao      varchar(255) NOT NULL,
  estoque        double precision NOT NULL DEFAULT 0,
  preco_unitario numeric(12,4) NOT NULL DEFAULT 0,
  preco_compra   numeric(12,4) NOT NULL DEFAULT 0,
  preco_venda    numeric(12,4) NOT NULL DEFAULT 0,
  idfornecedor   integer NULL,
  CONSTRAINT produtos_filial_pkey PRIMARY KEY (filial_id, produto_id),
  CONSTRAINT fk_produtos_fornecedor FOREIGN KEY (idfornecedor)
    REFERENCES fornecedor (idfornecedor)
);

CREATE TABLE venda (
  venda_id       bigint       NOT NULL,
  data_emissao   date         NOT NULL,
  horariomov     varchar(8)   NOT NULL DEFAULT '00:00:00',
  produto_id     varchar(25)  NOT NULL DEFAULT '',
  qtde_vendida   double precision NULL,
  valor_unitario numeric(12,4) NOT NULL DEFAULT 0,
  filial_id      integer      NOT NULL DEFAULT 1,
  item           integer      NOT NULL DEFAULT 0,
  unidade_medida varchar(3)   NULL,
  CONSTRAINT pk_venda PRIMARY KEY (filial_id, venda_id, data_emissao, produto_id, item, horariomov)
);

CREATE TABLE pedido_compra (
  pedido_id         bigint       NOT NULL DEFAULT 0,
  data_pedido       date         NULL,
  item              integer      NOT NULL DEFAULT 0,
  produto_id        varchar(25)  NOT NULL DEFAULT '0',
  descricao_produto varchar(255) NULL,
  ordem_compra      bigint       NOT NULL DEFAULT 0,
  qtde_pedida       double precision NULL,
  filial_id         integer      NULL,
  data_entrega      date         NULL,
  qtde_entregue     double precision NOT NULL DEFAULT 0,
  qtde_pendente     double precision NOT NULL DEFAULT 0,
  preco_compra      numeric(12,4) NULL DEFAULT 0,
  fornecedor_id     integer      NULL,
  CONSTRAINT pedido_compra_pkey PRIMARY KEY (pedido_id, produto_id, item),
  CONSTRAINT fk_pedido_fornecedor FOREIGN KEY (fornecedor_id)
    REFERENCES fornecedor (idfornecedor)
);

CREATE TABLE entradas_mercadoria (
  data_entrada      date         NULL,
  nro_nfe           varchar(255) NOT NULL,
  item              integer      NOT NULL DEFAULT 0,
  produto_id        varchar(25)  NOT NULL DEFAULT '0',
  descricao_produto varchar(255) NULL,
  ordem_compra      bigint       NOT NULL DEFAULT 0,
  qtde_recebida     double precision NULL,
  filial_id         integer      NULL,
  custo_unitario    numeric(12,4) NOT NULL DEFAULT 0,
  CONSTRAINT entradas_mercadoria_pkey PRIMARY KEY (ordem_compra, item, produto_id, nro_nfe)
);
