-- 1. CONCATENAR CÓDIGO E DESCRIÇÃO DOS PRODUTOS

SELECT
    produto_id || ' - ' || descricao_produto AS produto,
    qtde_pedida
FROM pedido_compra
WHERE descricao_produto IS NOT NULL
ORDER BY produto_id;

-- 2. FORMATAR DATAS PARA DD/MM/YYYY

SELECT
    pedido_id,
    produto_id || ' - ' || descricao_produto AS produto,
    qtde_pedida,
    TO_CHAR(data_pedido, 'DD/MM/YYYY') AS data_solicitacao,
    TO_CHAR(data_entrega, 'DD/MM/YYYY') AS data_entrega
FROM pedido_compra
ORDER BY data_pedido;

-- 3. PRODUTOS COM MAIS DE 10 UNIDADES REQUISITADAS

SELECT
    produto_id || ' - ' || MAX(descricao_produto) AS produto,
    SUM(qtde_pedida) AS quantidade_requisitada
FROM pedido_compra
WHERE data_pedido IS NOT NULL
GROUP BY produto_id
HAVING SUM(qtde_pedida) > 10
ORDER BY quantidade_requisitada DESC;



